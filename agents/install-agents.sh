#!/bin/sh
# Link the rules and the skills into Codex, Claude Code, Cursor, and Pi.
# Usage: ./agents/install-agents.sh [COMPANY]
# If you do not give a company, the script keeps the company that is installed, if there is one.
# The script does not replace a path that exists and points to a different target. It prints a message about that path.
set -eu
: "${HOME:?HOME must be set and must not be empty}"

# Use the real folder, so that the links stay correct when you run the script through a symlink.
src="$(CDPATH='' cd -P -- "$(dirname -- "$(realpath -- "$0")")" && pwd -P)"
base_rules="$(CDPATH='' cd -P -- "$src/.." && pwd -P)/AGENTS.md"
codex_dir="${CODEX_HOME:-$HOME/.codex}"
pi_dir="${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
# Pi expands "~" in PI_CODING_AGENT_DIR. Do the same here.
case "$pi_dir" in
    "~"*) pi_dir="$HOME${pi_dir#\~}" ;;
esac
claude_company_rules="$HOME/.claude/rules/company.md"
# Codex and Pi read one global rules file. Thus, each gets a copy with the company rules.
codex_override="$codex_dir/AGENTS.override.md"
pi_override="$pi_dir/AGENTS.override.md"
marker_prefix="<!-- Generated by zdotfiles agents/install-agents.sh for company:"
# Find the claude command in PATH. cmux adds a claude wrapper to PATH in its terminals.
# The wrapper does not show that Claude Code is installed, so the script skips its folder.
claude_installed=no
old_ifs="$IFS"
IFS=:
for path_dir in $PATH; do
    case "$path_dir" in
        */cmux-cli-shims/*) continue ;;
    esac
    if [ -x "$path_dir/claude" ]; then
        claude_installed=yes
        break
    fi
done
IFS="$old_ifs"

fail() {
    echo "error: $1" >&2
    exit 1
}

# Link the target in $1 to the path in $2.
link() {
    if [ "$(readlink "$2" 2>/dev/null)" = "$1" ]; then
        echo "ok    $2"
        return
    fi
    if [ -e "$2" ] || [ -L "$2" ]; then
        echo "skip  $2 (the path exists. Move it. Run the script again.)"
        return
    fi
    mkdir -p "$(dirname "$2")"
    ln -s "$1" "$2"
    echo "link  $2 -> $1"
}

# Make a link for each skill folder in $1, so that the other skills in the harness folders stay.
# Cursor also reads ~/.claude/skills. Thus, the script links there only when Claude Code is installed.
link_skills() {
    for skill_dir in "$1"/*/; do
        [ -d "$skill_dir" ] || continue
        skill_dir="${skill_dir%/}"
        link "$skill_dir" "$HOME/.agents/skills/$(basename "$skill_dir")" # Codex, Cursor, and Pi
        if [ "$claude_installed" = yes ]; then
            link "$skill_dir" "$HOME/.claude/skills/$(basename "$skill_dir")" # Claude Code
        fi
    done
}

# Delete each skill link that points into this folder to a skill that does not exist now.
# This removes the links of a skill that you renamed or deleted. Other links stay.
# If Claude Code is not installed, also delete each link in ~/.claude/skills that points into this folder.
prune_skills() {
    for harness_dir in "$HOME/.agents/skills" "$HOME/.claude/skills"; do
        for skill_link in "$harness_dir"/*; do
            [ -L "$skill_link" ] || continue
            link_target="$(readlink "$skill_link")"
            case "$link_target" in
                "$src/"*)
                    if [ ! -e "$link_target" ]; then
                        rm -- "$skill_link"
                        echo "prune $skill_link (the skill does not exist)"
                    elif [ "$harness_dir" = "$HOME/.claude/skills" ] && [ "$claude_installed" = no ]; then
                        rm -- "$skill_link"
                        echo "prune $skill_link (Claude Code is not installed)"
                    fi
                    ;;
            esac
        done
    done
}

# Return 0 if the file in $1 starts with the marker of this script.
is_generated() {
    case "$(head -n 1 "$1")" in
        "$marker_prefix"*) return 0 ;;
        *) return 1 ;;
    esac
}

# Print the company name from the marker in the first generated copy. If there is no marker, print nothing.
installed_company() {
    for override in "$codex_override" "$pi_override"; do
        [ -f "$override" ] || continue
        is_generated "$override" || continue
        first_line="$(head -n 1 "$override")"
        first_line="${first_line#"$marker_prefix" }"
        echo "${first_line%% *}"
        return
    done
}

# Write the copy of the rules for the company in $1 to the path in $2.
write_override() {
    if [ -L "$2" ]; then
        fail "$2 is a symlink. Move it. Run the script again."
    fi
    if [ -e "$2" ] && ! is_generated "$2"; then
        echo "skip  $2 (the path exists, and this script did not make it. Move it. Run the script again.)"
        return
    fi
    mkdir -p "$(dirname "$2")"
    {
        echo "$marker_prefix $1 -->"
        edit_note="Edit AGENTS.md or companies/$1/RULES.md. Then run install-agents.sh again."
        echo "<!-- Do not edit this file. $edit_note -->"
        echo
        cat "$base_rules"
        echo
        cat "$src/companies/$1/RULES.md"
    } >"$2"
    echo "write $2"
}

# Stop before any write if a skill folder name in $1 breaks the Agent Skills name rule.
check_skill_names() {
    for skill_dir in "$1"/*/; do
        [ -d "$skill_dir" ] || continue
        skill_name="$(basename "$skill_dir")"
        printf '%s\n' "$skill_name" | grep -Eqx '[a-z0-9]+(-[a-z0-9]+)*' ||
            fail "skill folder $skill_name is not a correct skill name."
    done
}

check_harness_folders() {
    case "$codex_dir" in
        /*) ;;
        *) fail "CODEX_HOME must be an absolute path." ;;
    esac
    case "$pi_dir" in
        /*) ;;
        *) fail "PI_CODING_AGENT_DIR must be an absolute path." ;;
    esac
    for harness_dir in "$HOME/.claude/skills" "$HOME/.claude/rules" "$HOME/.agents/skills"; do
        if [ -L "$harness_dir" ]; then
            fail "$harness_dir is a symlink to $(readlink "$harness_dir"). Make it a real folder. Run the script again."
        fi
    done
}

# Stop before any write if the company in $1 cannot be installed.
check_company() {
    company_dir="$src/companies/$1"
    printf '%s\n' "$1" | grep -Eqx '[A-Za-z0-9][A-Za-z0-9._-]*' ||
        fail "give a folder name in companies/, not a path."
    current="$(installed_company)"
    if [ ! -f "$company_dir/RULES.md" ] && [ "$1" = "$current" ]; then
        fail "the copies name company $1, but $company_dir does not exist. Delete the copies. Run the script again."
    fi
    [ -f "$company_dir/RULES.md" ] || fail "$company_dir/RULES.md does not exist. Copy companies/_template first."
    if { [ -e "$claude_company_rules" ] || [ -L "$claude_company_rules" ]; } &&
        [ "$(readlink "$claude_company_rules")" != "$company_dir/RULES.md" ]; then
        fail "$claude_company_rules exists and is not the rules of company $1. Move it. Run the script again."
    fi
    for override in "$codex_override" "$pi_override"; do
        if [ -L "$override" ]; then
            fail "$override is a symlink. Move it. Run the script again."
        fi
    done
    if [ -n "$current" ] && [ "$current" != "$1" ]; then
        fail "company $current is installed. Delete its links and copies first. agents/README.md lists them."
    fi
    for skill_dir in "$company_dir"/skills/*/; do
        [ -d "$skill_dir" ] || continue
        skill_dir="${skill_dir%/}"
        skill_name="$(basename "$skill_dir")"
        if [ -e "$src/skills/$skill_name" ]; then
            fail "company skill $skill_name has the same name as a shared skill."
        fi
        for skill_link in "$HOME/.agents/skills/$skill_name" "$HOME/.claude/skills/$skill_name"; do
            if { [ -e "$skill_link" ] || [ -L "$skill_link" ]; } &&
                [ "$(readlink "$skill_link")" != "$skill_dir" ]; then
                fail "$skill_link exists and is not this company skill. Move it. Run the script again."
            fi
        done
    done
}

install_company() {
    link "$src/companies/$1/RULES.md" "$claude_company_rules" # Claude Code rules
    write_override "$1" "$codex_override"                     # Codex rules
    write_override "$1" "$pi_override"                        # Pi rules
    link_skills "$src/companies/$1/skills"
    echo "Cursor: paste $src/companies/$1/RULES.md after the root AGENTS.md in Customize > Rules."
}

company="${1:-$(installed_company)}"
check_harness_folders
check_skill_names "$src/skills"
if [ -n "$company" ]; then
    check_company "$company"
    check_skill_names "$src/companies/$company/skills"
fi

link "$base_rules" "$codex_dir/AGENTS.md"    # Codex rules
link "$base_rules" "$HOME/.claude/CLAUDE.md" # Claude Code rules
link "$base_rules" "$pi_dir/AGENTS.md"       # Pi rules
prune_skills
if [ "$claude_installed" = no ]; then
    echo "skip  $HOME/.claude/skills (claude was not found. Install Claude Code. Run the script again.)"
fi
link_skills "$src/skills"

# Cursor reads the AGENTS.md of each project. For global rules, paste the file into Cursor.
echo "Cursor: paste $base_rules into Customize > Rules."

if [ -n "$company" ]; then
    install_company "$company"
fi
